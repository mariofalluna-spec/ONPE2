/**
 * Normaliza nombres de distritos para comparación segura
 */
function normalizeDistrictName(name: string): string {
  return name
    .toLowerCase()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .trim();
}

/**
 * Obtiene los RLV asignados a un distrito específico
 */
export function getRLVsByDistrito(distritoNombre: string): RLVInfo[] {
  const normalized = normalizeDistrictName(distritoNombre);
  return LISTA_RLV.filter(rlv => {
    const rlvNorm = normalizeDistrictName(rlv.distrito);
    return rlvNorm === normalized || rlvNorm.replace(/\s+/g, '') === normalized.replace(/\s+/g, '');
  });
}

/**
 * Obtiene los RLVs agrupados por distrito
 */
export function getRLVsAgrupadosPorDistrito(): { distrito: string; provincia: string; rlvs: RLVInfo[] }[] {
  const gruposMap = new Map<string, { distrito: string; provincia: string; rlvs: RLVInfo[] }>();

  LISTA_RLV.forEach(rlv => {
    if (!gruposMap.has(rlv.distrito)) {
      gruposMap.set(rlv.distrito, {
        distrito: rlv.distrito,
        provincia: rlv.provincia,
        rlvs: [],
      });
    }
    gruposMap.get(rlv.distrito)!.rlvs.push(rlv);
  });

  return Array.from(gruposMap.values());
}
