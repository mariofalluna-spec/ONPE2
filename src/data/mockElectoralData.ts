// Helper to generate mesas for all 31 districts
function buildInitialMesas(): MesaElectoral[] {
  const result: MesaElectoral[] = [];

  LISTA_31_DISTRITOS.forEach((dist, distIdx) => {
    const baseMesaNum = 48000 + dist.id * 10;

    for (let m = 1; m <= dist.mesasCount; m++) {
      const mesaNumStr = String(baseMesaNum + m).padStart(6, '0');
      const mesaId = `mesa-${mesaNumStr}`;

      result.push({
        id: mesaId,
        numeroMesa: mesaNumStr,
        departamento: 'Ica',
        provincia: dist.provincia,
        distrito: dist.nombre,
        localVotacion: dist.localPrincipal,
        direccion: dist.direccion,
        pabellon: m <= 2 ? 'Pabellón A' : 'Pabellón B',
        aula: `Aula ${100 + m} - Piso ${m <= 2 ? 1 : 2}`,
        piso: m <= 2 ? 'Piso 1' : 'Piso 2',
        coordinadorDistrital: {
          id: `coord-${dist.id}`,
          nombre: dist.coordinadorNombre,
          cargo: 'Coordinador Distrital',
          telefono: dist.coordinadorTelefono,
          email: dist.coordinadorEmail,
          distrito: dist.nombre,
          disponible: true,
          nota: `Coordinador asignado a la jurisdicción de ${dist.nombre} (${dist.provincia})`,
        },
        miembrosMesa: [
          {
            id: `mb-${mesaNumStr}-1`,
            nombre: `Presidente Mesa ${mesaNumStr}`,
            cargo: 'Presidente de Mesa',
            telefono: `+51956${dist.id.toString().padStart(2, '0')}${m.toString().padStart(2, '0')}1`,
            dni: `${40000000 + dist.id * 1000 + m * 11}`,
            disponible: true,
            nota: 'Titular en mesa desde apertura',
          },
          {
            id: `mb-${mesaNumStr}-2`,
            nombre: `Secretario(a) Mesa ${mesaNumStr}`,
            cargo: 'Secretario',
            telefono: `+51956${dist.id.toString().padStart(2, '0')}${m.toString().padStart(2, '0')}2`,
            dni: `${41000000 + dist.id * 1000 + m * 13}`,
            disponible: true,
          },
          {
            id: `mb-${mesaNumStr}-3`,
            nombre: `Tercer Miembro Mesa ${mesaNumStr}`,
            cargo: 'Tercer Miembro',
            telefono: `+51956${dist.id.toString().padStart(2, '0')}${m.toString().padStart(2, '0')}3`,
            dni: `${42000000 + dist.id * 1000 + m * 17}`,
            disponible: true,
          },
          {
            id: `mb-${mesaNumStr}-4`,
            nombre: `Primer Suplente Mesa ${mesaNumStr}`,
            cargo: 'Primer Suplente',
            telefono: `+51956${dist.id.toString().padStart(2, '0')}${m.toString().padStart(2, '0')}4`,
            dni: `${43000000 + dist.id * 1000 + m * 19}`,
            disponible: true,
          },
        ],
        otrosAsignados: [
          {
            id: `asig-${mesaNumStr}-1`,
            nombre: `Fiscalizador JNE ${dist.nombre}`,
            cargo: 'Fiscalizador',
            telefono: `+51956${dist.id.toString().padStart(2, '0')}${m.toString().padStart(2, '0')}5`,
            disponible: true,
            nota: 'Fiscalizador oficial asignado al local',
          },
          {
            id: `asig-${mesaNumStr}-2`,
            nombre: `Personero Acreditado M${mesaNumStr}`,
            cargo: 'Personero / Asignado',
            telefono: `+51956${dist.id.toString().padStart(2, '0')}${m.toString().padStart(2, '0')}6`,
            disponible: true,
          },
          ...(m === 1
            ? [
                ...getCLVsByDistrito(dist.nombre).map((clv): ContactoElectoral => ({
                  id: `asig-clv-${clv.id}`,
                  nombre: clv.nombreCompleto,
                  cargo: 'Coordinador de Local (CLV)',
                  telefono: clv.telefono,
                  distrito: dist.nombre,
                  localVotacion: dist.localPrincipal,
                  disponible: true,
                  nota: `CLV Asignado al distrito de ${dist.nombre}`,
                })),
                ...getRLVsByDistrito(dist.nombre).map((rlv): ContactoElectoral => ({
                  id: `asig-rlv-${rlv.id}`,
                  nombre: rlv.nombreCompleto,
                  cargo: 'Responsable de Local (RLV)',
                  telefono: rlv.telefono,
                  distrito: dist.nombre,
                  localVotacion: dist.localPrincipal,
                  disponible: true,
                  nota: `RLV Asignado al distrito de ${dist.nombre}`,
                })),
                ...getCMsByDistrito(dist.nombre).map((cm): ContactoElectoral => ({
                  id: `asig-cm-${cm.id}`,
                  nombre: cm.nombreCompleto,
                  cargo: 'Coordinador de Mesa (CM)',
                  telefono: cm.telefono,
                  distrito: dist.nombre,
                  localVotacion: dist.localPrincipal,
                  disponible: true,
                  nota: `CM Asignado al distrito de ${dist.nombre}`,
                })),
              ]
            : []),
        ],
        observacionContacto: `Mesa ${mesaNumStr} ubicada en ${dist.localPrincipal}, ${dist.nombre}.`,
      });
    }
  });

  return result;
}

export const INITIAL_MESAS: MesaElectoral[] = buildInitialMesas();
